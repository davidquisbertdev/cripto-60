-- Operaciones de SWING (días a semanas) guardadas en la cuenta: el plan con el que se entró (entrada, SL,
-- TP1, trailing) y los eventos que registra el usuario (entradas y salidas, totales o parciales), para volver
-- días después y ver si se acerca al TP1, si rompió el SL o si toca mover el SL.
create table public.swing_operaciones (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  base text not null check (char_length(base) between 2 and 20),
  lado text not null check (lado in ('LONG', 'SHORT')),
  setup text,
  entrada numeric not null check (entrada > 0),
  sl numeric not null check (sl > 0),
  tp1 numeric check (tp1 is null or tp1 > 0),
  trailing boolean not null default true,
  abierta_en timestamptz not null default now(),
  cerrada_en timestamptz,
  eventos jsonb not null default '[]'::jsonb,
  nota text check (nota is null or char_length(nota) <= 500),
  creada timestamptz not null default now()
);
create index swing_operaciones_usuario on public.swing_operaciones (user_id, cerrada_en);

alter table public.swing_operaciones enable row level security;
create policy "swing propias" on public.swing_operaciones for all using (user_id = auth.uid()) with check (user_id = auth.uid());
